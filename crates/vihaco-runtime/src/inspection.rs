use std::{any::Any, fmt::Debug};

/// Inspect a resolved instruction without depending on its generated enum variant.
pub trait InspectInstruction {
    fn inspect<R>(&self, inspect: impl FnOnce(InstructionView<'_>) -> R) -> R;
}

/// A resolved instruction's canonical route and operands in declaration order.
pub struct InstructionView<'a> {
    pub device_path: &'static [&'static str],
    pub dialect: &'static str,
    pub mnemonic: &'static str,
    /// Operand borrows are unavailable when the instruction is packed.
    pub operands: Option<&'a [InstructionOperand<'a>]>,
    pub leaf: &'a dyn Debug,
}

/// A borrow of a resolved operand with its original Rust type.
pub struct InstructionOperand<'a> {
    pub debug: &'a dyn Debug,
    pub value: &'a dyn Any,
}

/// Generated by the dialect macro for use by composite instruction inspection.
#[doc(hidden)]
pub trait InspectOperands {
    fn inspect_operands<R>(
        &self,
        inspect: impl FnOnce(Option<&[InstructionOperand<'_>]>) -> R,
    ) -> R;
}
