use vihaco_bytecode::{BytecodeSectionView, SstSectionView};

/// Allow a machine to load the bytecode data owned directly by its section.
///
/// When used with the [`vihaco_runtime_derive::composite`] macro, this hook runs before
/// generated child-section forwarding. Implement this for each composite to
/// make its own section behavior explicit, even when that behavior is a no-op.
/// Return program data to an outer owner rather than storing it inside Dispatch.
/// Existing loaders that only mutate their receiver use `type Output = ();`.
pub trait LoadOwnBytecodeSection<C> {
    /// The artifact produced for this section, or `()` for a loader that stores it.
    type Output;

    fn load_own_bytecode_section<'bc>(
        &mut self,
        section: BytecodeSectionView<'bc, C>,
    ) -> eyre::Result<Self::Output>;
}

/// Allow a machine to load the SST data owned directly by its section.
///
/// When used with the [`vihaco_runtime_derive::composite`] macro, this hook runs before
/// generated child-section forwarding. Implement this for each composite to
/// make its own section behavior explicit, even when that behavior is a no-op.
/// Return program data to an outer owner rather than storing it inside Dispatch.
/// Existing loaders that only mutate their receiver use `type Output = ();`.
pub trait LoadOwnSstSection<C> {
    /// The artifact produced for this section, or `()` for a loader that stores it.
    type Output;

    fn load_own_sst_section<'bc>(
        &mut self,
        section: SstSectionView<'bc, C>,
    ) -> eyre::Result<Self::Output>;

    /// Lower a section's parsed instructions after preparing loader capabilities.
    ///
    /// Call this from `load_own_sst_section` before storing executable code.
    /// For a generated composite syntax aggregate, the single `Lower<Self>`
    /// bound requires every included instruction's loader capabilities. An
    /// error returns no partial instruction vector.
    fn lower_instructions<I>(
        &mut self,
        instructions: impl IntoIterator<Item = I>,
    ) -> eyre::Result<Vec<I::Runtime>>
    where
        I: vihaco_abi::Lower<Self>,
    {
        instructions
            .into_iter()
            .map(|instruction| instruction.lower(self))
            .collect()
    }
}

/// Allow a machine to load a bytecode section completely.
///
/// For composites generated by [`vihaco_runtime_derive::composite`], this loads the
/// composite's own section through [`LoadOwnBytecodeSection`] and then forwards
/// direct child sections to `#[loadable]` devices. The generated implementation
/// returns the own-section output after all child loads succeed. Loadable children
/// use `Output = ()`: an authored owner stores each child artifact internally.
///
/// Loading is not transactional. On error, no output is returned, but earlier
/// mutations to this loader or already-loaded children are retained.
pub trait LoadBytecodeSection<C> {
    /// The artifact produced for this section, or `()` for a loader that stores it.
    type Output;

    fn load_bytecode_section<'bc>(
        &mut self,
        section: BytecodeSectionView<'bc, C>,
    ) -> eyre::Result<Self::Output>;
}

